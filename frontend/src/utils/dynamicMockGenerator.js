// Dynamic test generation engine
export const generateDynamicMpscTest = ({
  subject = 'all',
  questionCount = 20,
  markingScheme = 'mpsc_rajyaseva',
  timeLimit = null,
  topic = '',
  testIndex = null
}) => {
  let pool = [...MPSC_MASTER_QUESTION_POOL];

  // Subject filtering
  if (subject !== 'all') {
    const subNormalized = subject.toLowerCase();
    pool = pool.filter(q => (q.subject || '').toLowerCase().includes(subNormalized));
    if (pool.length === 0) {
      pool = [...MPSC_MASTER_QUESTION_POOL];
    }
  }

  // Shuffle master pool
  const shuffledPool = [...pool].sort(() => Math.random() - 0.5);
  
  // Pick requested question count (cycle if user requests large counts like 50 or 100)
  let selectedQuestions = [];
  while (selectedQuestions.length < questionCount) {
    const needed = questionCount - selectedQuestions.length;
    const batch = [...shuffledPool].sort(() => Math.random() - 0.5);
    selectedQuestions = [...selectedQuestions, ...batch.slice(0, needed)];
  }

  // Anti-cheat: Shuffle options for each question
  const randomizedQuestions = selectedQuestions.map((q, idx) => {
    const originalOptions = [...q.options];
    const correctVal = originalOptions[q.correctOption];
    const shuffledOptions = [...originalOptions].sort(() => Math.random() - 0.5);
    const newCorrectIdx = shuffledOptions.indexOf(correctVal);

    return {
      question: q.question,
      options: shuffledOptions,
      correctOption: newCorrectIdx !== -1 ? newCorrectIdx : 0,
      explanation: q.explanation || '',
      subject: q.subject || 'MPSC GS',
      originalQIndex: idx
    };
  });

  const count = randomizedQuestions.length;
  const isGroupC = markingScheme === 'group_c';
  const marksPerQ = isGroupC ? 1.0 : 2.0;
  const totalMarks = count * marksPerQ;
  const allocatedTime = timeLimit || (count >= 100 ? 120 : count >= 50 ? 60 : count >= 25 ? 30 : 20);

  const subjectLabel = subject === 'all' ? 'सर्वसमावेशक सामान्य अध्ययन' : subject;
  const uniqueId = `dynamic_mock_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`;
  const title = testIndex ? `Mock Test ${testIndex}` : `Mock Test`;

  return {
    id: uniqueId,
    _id: uniqueId,
    title,
    subject: subjectLabel,
    topic: topic || `${subjectLabel} सराव परीक्षा (${count} प्रश्न)`,
    timeLimit: allocatedTime,
    markingScheme,
    totalMarks,
    marksPerQuestion: marksPerQ,
    penaltyPerQuestion: isGroupC ? 0.25 : 0.66,
    examDate: new Date().toLocaleDateString('mr-IN'),
    formattedDate: new Date().toISOString().split('T')[0],
    isDynamic: true,
    createdBy: 'Dynamic AI Engine',
    creatorName: 'MPSC Simulator Engine',
    createdAt: new Date().toISOString(),
    attemptedBy: [],
    questions: randomizedQuestions
  };
};
